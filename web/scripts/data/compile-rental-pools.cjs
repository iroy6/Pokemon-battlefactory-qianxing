// Compile feasible tactical plans and bounded-search witnesses, not rental sets.
const fs=require('fs'),path=require('path');
process.chdir(path.resolve(__dirname,'../..'));
const P=JSON.parse(fs.readFileSync(0,'utf8'));
const divisionPolicy=P.divisionPolicy;delete P.divisionPolicy;
global.FactoryRentalPools=P;
const D=require('../../data/species.json'),M=require('../../src/data/meta.js');
const toID=x=>String(x).toLowerCase().replace(/[^a-z0-9]/g,'');
global.FactoryData={...D,toID};
const G=require('../../src/game/rental-generator.js');
let plans=0,cohorts=0;
for(const base of D.sets){
 const row=P.species[base.num],spec=M.species[toID(base.species)];
 for(const c of row.cohorts){
  c.lanes=c.lanes.map(l=>G.compileLane(c,l,spec)).filter(l=>l.plans.length);
  delete c.support;
 }
 // Do not roll an inferior attack direction with no STAB if another viable
 // direction has one. Only species lacking implemented STAB altogether keep
 // their legal coverage-based plans.
 const hasStab=row.cohorts.some(c=>c.lanes.some(l=>l.requireStab));
 if(hasStab)for(const c of row.cohorts)c.lanes=c.lanes.filter(l=>l.requireStab);
 row.cohorts=row.cohorts.filter(c=>c.lanes.length);
 if(!row.cohorts.length)throw Error('No coherent four-move plan for '+base.num+' '+base.name);
 for(const c of row.cohorts){cohorts++;for(const lane of c.lanes)plans+=lane.plans.length;}
}
const js='/* Generated by scripts/data/build_rental_pools.py. */\n(function(root){const pools='+JSON.stringify(P)+';root.FactoryRentalPools=pools;if(typeof module!=="undefined")module.exports=pools;})(typeof window!=="undefined"?window:globalThis);\n';
fs.writeFileSync('src/data/rental-pools.js',js);
const live={sets:D.sets.map(base=>{
 const assignment=divisionPolicy.species[base.num];return {...base,pool:assignment.pool,evolutionStage:assignment.stage};
}),moveNames:D.moveNames,types:D.types,divisions:divisionPolicy.divisions,divisionPolicyVersion:divisionPolicy.version};
fs.writeFileSync('src/data/species-data.js','/* Generated from data/species.json and data/config/division-policy.json. */\n(function(root){const data='+JSON.stringify(live)+';data.speciesSets=data.sets;data.toID=x=>String(x).toLowerCase().replace(/[^a-z0-9]/g,"");root.FactoryData=data;if(typeof module!=="undefined")module.exports=data;})(typeof window!=="undefined"?window:globalThis);\n');
console.log(`Built partial learnsets: ${D.sets.length} species, ${cohorts} version cohorts, ${plans} tactical plans.`);
